        device: str = "auto",
        # KG source toggle:
        #   "drugbank" (default): use train.kg 5-bucket schema (legacy)
        #   "merged"            : use merged DrugBank+Hetionet+PrimeKG parquet,
        #                         requires `merged_kg_path` (path to edges parquet)
        backbone_kg_source: str = "drugbank",
        merged_kg_path: str | Path | None = None,
        merged_kg_blocklist: tuple[str, ...] = (),
        # Paper-faithful additions (CLAUDE.md §baseline-from-reproduction):
        # weight_decay matches paper hyperopt S1/S2 best (1e-8).
