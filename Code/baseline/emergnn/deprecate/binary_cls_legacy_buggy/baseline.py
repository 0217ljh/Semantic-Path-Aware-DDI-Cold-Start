"""EmerGNN thin adapter — implementation of :class:`BaselineModel`.

NOTE — paper-vs-port task formulation:
  * Original paper (Zhang et al., Nat Comp Sci 2023) on DrugBank does
    **multi-class** (predict-which-of-86-types, softmax margin loss,
    macro F1 / ACC / Cohen κ). The MULTI-CLASS task is in the parent
    paper; see ``baseline_multiclass.py`` for that variant.
  * THIS binary adapter is a ColdDDI-aligned simplification for
    cold-start S0/S1/S2 binary AUC/F1 evaluation. Negative samples are
    generated by drug replacement (ColdDDI protocol), NOT from the
    paper's multi-class formulation.

Wraps the verbatim research-repo modules
:mod:`baseline.emergnn.model` (the pure-PyTorch reimplementation
of EmerGNN — no torchdrug / torch_scatter required),
:mod:`baseline.emergnn.kg_builder` (KG → triplet table), and
:mod:`baseline.emergnn.morgan_features` (Morgan-FP entity feats).

The adapter is responsible for two bridges:

* :class:`data_utils.kg.KnowledgeGraph` → the legacy ``my_X_list``
  dict the source kg_builder consumes.
* :class:`data_utils.dataset.PairDataset` train/val/test rows → the
  per-pair head/tail entity indices the EmerGNN forward pass expects.

Like :class:`baseline.deepddi.DeepDDIBaseline`, this module is
the **template** for any KG-aware baseline: cast the KG once at fit
time, keep entity-id → index lookup as state, batch over
``DataFrame[drug_a_id, drug_b_id]`` for predict.
"""

